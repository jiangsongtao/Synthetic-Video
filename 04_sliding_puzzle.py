# --- 2. Helper Functions (auxiliary function) ---

def generate_position_options(correct_answer, all_positions, none_option=None):
    """Build location options"""
    options = [correct_answer]
    possible_decoys = set(all_positions) - {correct_answer}

    if none_option and correct_answer != none_option:
        options.append(none_option)

    num_decoys_needed = 4 - len(options)
    if possible_decoys: # Protect
        options.extend(random.sample(list(possible_decoys), min(len(possible_decoys), num_decoys_needed)))

    while len(options) < 4:
        available_decoys = list(set(all_positions) - set(options))
        if not available_decoys:
             options.append(f"Decoy_{len(options)}")
        else:
             options.append(random.choice(available_decoys))

    random.shuffle(options)
    return options

def generate_numeric_options(correct_answer, max_val):
    """Generate number options (infinite loop fixed)"""
    correct_answer = str(correct_answer)
    options = {correct_answer}
    possible_decoys = set(str(i) for i in range(max_val + 1)) - {correct_answer}

    while len(options) < 4 and possible_decoys:
        options.add(possible_decoys.pop())

    i = max_val + 1
    while len(options) < 4:
        options.add(str(i))
        i += 1

    options = list(options)
    random.shuffle(options)
    return options


# --- 3. Puzzle State Engine (Core: Puzzle Truth Engine) ---

class PuzzleState:
    """
Maintain the internal state (truth value) of the sliding puzzle.
    """
    # [--- 已修复 ---] Fixed initialization order of __init__
    def __init__(self, grid_size=GRID_SIZE):
        self.grid_size = grid_size
        self._generate_maps()

        # 1. Initialize the history immediately so that self.move() can use them during shuffle
        self.move_history = []
        self.board_history = [] # Set to empty first

        # 2. Create a solved board
        self.board = np.arange(1, grid_size * grid_size + 1).reshape((grid_size, grid_size))
        self.board[self.board == grid_size * grid_size] = EMPTY_SLOT_ID # Set the last one to empty
        self.empty_pos = tuple(np.argwhere(self.board == EMPTY_SLOT_ID)[0])
        self.board_history.append(self.board.copy()) # Store "solved" status

        # 3. "Scramble" it to create the "initial state" of the video
        self.shuffle(num_moves=100) # Increase the number of shuffles to accommodate 4x4

        # 4. Store this initial state
        self.initial_board = self.board.copy()
        self.initial_empty_pos = self.empty_pos

        # 5. The operation of clearing history has been moved to generate_operation_sequence().
        # This ensures that the history produced by shuffle is cleared.

    def _generate_maps(self):
        """Generate mapping between coordinates, indices and labels"""
        self.pos_to_label = {} # (0, 0) -> 'a1'
        self.label_to_pos = {} # 'a1' -> (0, 0)
        self.pos_to_coord = {} # (0, 0) -> (1, 4) [for plotting]

        row_labels = [chr(ord('a') + i) for i in range(self.grid_size)]
        col_labels = [str(i + 1) for i in range(self.grid_size)]

        for r, r_label in enumerate(row_labels):
            for c, c_label in enumerate(col_labels):
                key = f"{r_label}{c_label}"
                self.pos_to_label[(r, c)] = key
                self.label_to_pos[key] = (r, c)
                # [--- 视觉修复 ---]
                self.pos_to_coord[(r, c)] = (c + 1, self.grid_size - r)

    def get_valid_moves(self):
        """Get the positions (indexes) of all blocks that can be moved to empty spaces"""
        r, c = self.empty_pos
        moves = []
        for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
            nr, nc = r + dr, c + dc
            if 0 <= nr < self.grid_size and 0 <= nc < self.grid_size:
                moves.append((nr, nc))
        return moves

    def move(self, tile_pos):
        """Move a block to the current empty space"""
        if tile_pos not in self.get_valid_moves():
            return # illegal movement

        tile_r, tile_c = tile_pos
        empty_r, empty_c = self.empty_pos

        # Get true value
        tile_id = self.board[tile_r, tile_c]

        # exchange
        self.board[empty_r, empty_c] = tile_id
        self.board[tile_r, tile_c] = EMPTY_SLOT_ID

        # Update vacancies
        new_empty_pos = (tile_r, tile_c)

        # record history
        move_data = {
            'from': self.pos_to_label[tile_pos],
            'to': self.pos_to_label[self.empty_pos],
            'tile_id': int(tile_id)
        }
        self.move_history.append(move_data)
        self.board_history.append(self.board.copy())

        self.empty_pos = new_empty_pos

    def shuffle(self, num_moves):
        """Starting from the current state, move randomly N times (used to create the initial state)"""
        for _ in range(num_moves):
            valid_tiles = self.get_valid_moves()
            tile_to_move = random.choice(valid_tiles)
            self.move(tile_to_move)

    # [--- NEW ---] implements biased movement
    def generate_biased_sequence(self, num_ops, relevant_tile_id):
        """Generate the sequence of operations to be played in the video and move relevant_tile_id first"""
        # Make sure the history is clean and only contains the initial state
        self.move_history = []
        self.board_history = [self.initial_board.copy()]
        self.board = self.initial_board.copy()
        self.empty_pos = self.initial_empty_pos

        for _ in range(num_ops):
            valid_moves = self.get_valid_moves() # List of (r,c)

            # Find the *current* position of the relevant block (r,c)
            relevant_tile_pos = None
            if relevant_tile_id is not None:
                pos_array = np.argwhere(self.board == relevant_tile_id)
                if pos_array.size > 0:
                    relevant_tile_pos = tuple(pos_array[0])

            tile_to_move = None

            # Check if the relevant block *can* be moved
            if relevant_tile_pos and relevant_tile_pos in valid_moves:
                if random.random() < PROB_MOVE_RELEVANT:
                    # 70% probability: move the relevant block
                    tile_to_move = relevant_tile_pos
                else:
                    # 30% chance: choose from *other* movable blocks
                    other_moves = [m for m in valid_moves if m != relevant_tile_pos]
                    if other_moves:
                        tile_to_move = random.choice(other_moves)
                    else:
                        tile_to_move = relevant_tile_pos # It is the only one that moves

            # If no bias is applied (e.g. related blocks cannot move, or 30% random)
            if tile_to_move is None:
                tile_to_move = random.choice(valid_moves)

            self.move(tile_to_move)

        self.final_board = self.board.copy()

    def get_board_at_step(self, step):
        """Get the board status at step n"""
        if step < 0 or step >= len(self.board_history):
             return self.board_history[-1]
        return self.board_history[step]

# --- 4. Video Generation Engine (video generator) ---
class VideoGenerator:
    def __init__(self, puzzle_state):
        self.puzzle = puzzle_state
        self.grid_size = puzzle_state.grid_size
        self.fig, self.ax = plt.subplots(figsize=(6, 6))
        self.dynamic_patches = []

        self.row_labels = [chr(ord('a')+i) for i in range(self.grid_size)]
        self.col_labels = [str(i+1) for i in range(self.grid_size)]

    def _draw_grid_and_labels(self):
        """Draw background grid and a,b,c / 1,2,3 tags"""
        self.ax.clear()
        self.ax.set_aspect('equal')
        self.ax.set_xlim(0, self.grid_size + 1)
        self.ax.set_ylim(0, self.grid_size + 1)
        self.ax.axis('off')

        for i in range(self.grid_size + 1):
            self.ax.plot([i+0.5, i+0.5], [0.5, self.grid_size+0.5], color='black', lw=2)
            self.ax.plot([0.5, self.grid_size+0.5], [i+0.5, i+0.5], color='black', lw=2)

        for i, label in enumerate(self.col_labels):
            self.ax.text(i + 1, self.grid_size + 0.75, label, ha='center', va='center', fontsize=16, color='red')
        for i, label in enumerate(self.row_labels):
            self.ax.text(0.25, self.grid_size - i, label, ha='center', va='center', fontsize=16, color='red')

    def _draw_tile(self, center_pos, tile_id, is_revealed=False):
        """Draw a square at the specified center position"""
        if tile_id == EMPTY_SLOT_ID:
            return

        cx, cy = center_pos
        tile = patches.Rectangle(
            (cx - 0.45, cy - 0.45), 0.9, 0.9,
            facecolor='blue', edgecolor='black', lw=1, zorder=5
        )
        self.dynamic_patches.append(self.ax.add_patch(tile))

        if is_revealed:
            # [--- MODIFIED ---] Adjust font size to fit 4x4
            font_size = 24 if self.grid_size == 3 else 18
            self.dynamic_patches.append(
                self.ax.text(cx, cy, str(tile_id), ha='center', va='center', color='white', fontsize=font_size, weight='bold', zorder=10)
            )

    def _draw_arrow(self, from_coord, to_coord):
        """Draw a red moving arrow"""
        arrow = patches.FancyArrowPatch(
            from_coord, to_coord,
            color='red',
            arrowstyle='-|>,head_length=0.6,head_width=0.4',
            mutation_scale=20, lw=3, zorder=20
        )
        self.dynamic_patches.append(self.ax.add_patch(arrow))

    def _update(self, frame):
        [p.remove() for p in self.dynamic_patches]; self.dynamic_patches = []

        ops_history = self.puzzle.move_history
        num_ops = len(ops_history)
        frames_per_op = MOVE_DURATION_FRAMES + STATIC_DURATION_FRAMES
        total_op_frames = num_ops * frames_per_op

        # Phase 1: Moving process (only anonymous blocks shown)
        if frame < total_op_frames:
            op_idx = frame // frames_per_op
            frame_in_op = frame % frames_per_op

            if op_idx >= num_ops: # Protect
                self._draw_grid_and_labels()
                board_last = self.puzzle.get_board_at_step(-1)
                for (r,c), tile_id in np.ndenumerate(board_last):
                    self._draw_tile(self.puzzle.pos_to_coord[(r,c)], tile_id, is_revealed=False)
                return

            self._draw_grid_and_labels()

            move = ops_history[op_idx]
            board_before_move = self.puzzle.get_board_at_step(op_idx)
            board_after_move = self.puzzle.get_board_at_step(op_idx + 1)

            # 1a: On the move
            if frame_in_op < MOVE_DURATION_FRAMES:
                progress = frame_in_op / (MOVE_DURATION_FRAMES - 1) if MOVE_DURATION_FRAMES > 1 else 1.0

                from_pos = self.puzzle.label_to_pos[move['from']]
                to_pos = self.puzzle.label_to_pos[move['to']]
                from_coord = np.array(self.puzzle.pos_to_coord[from_pos])
                to_coord = np.array(self.puzzle.pos_to_coord[to_pos])

                anim_coord = from_coord + (to_coord - from_coord) * progress

                for (r,c), tile_id in np.ndenumerate(board_before_move):
                    if tile_id != EMPTY_SLOT_ID and tile_id != move['tile_id']:
                        self._draw_tile(self.puzzle.pos_to_coord[(r,c)], tile_id, is_revealed=False)

                self._draw_tile(anim_coord, move['tile_id'], is_revealed=False)
                self._draw_arrow(from_coord, to_coord)

            # 1b: Still after moving
            else:
                for (r,c), tile_id in np.ndenumerate(board_after_move):
                    self._draw_tile(self.puzzle.pos_to_coord[(r,c)], tile_id, is_revealed=False)

        # Phase 2: Final Reveal (Show Figures)
        else:
            self._draw_grid_and_labels()
            final_board = self.puzzle.final_board
            for (r,c), tile_id in np.ndenumerate(final_board):
                self._draw_tile(self.puzzle.pos_to_coord[(r,c)], tile_id, is_revealed=True)

    def generate_video(self):
        num_ops = len(self.puzzle.move_history)
        total_frames = num_ops * (MOVE_DURATION_FRAMES + STATIC_DURATION_FRAMES) + FINAL_REVEAL_FRAMES

        ani = animation.FuncAnimation(self.fig, self._update, frames=total_frames, interval=1000/FPS)

        writer = animation.writers['ffmpeg'](fps=FPS, metadata=dict(artist='Gemini'), bitrate=2000)

        # [--- 已修复 ---] increases try...finally ensuring plt.close() is called
        try:
            ani.save(self.data['video_filepath'], writer=writer, dpi=120)
        finally:
            plt.close(self.fig) # Regardless of success or failure, close the graph to prevent memory leaks

# --- 5. Challenge Generation Logic (Core: Challenge Generator) ---

def generate_challenge_data(challenge_id, challenge_type):

    # 1. Initialize the truth engine
    puzzle = PuzzleState(grid_size=GRID_SIZE)

    # 2. Identify relevant blocks
    num_ops = random.randint(25, 40) # [--- MODIFIED ---] Increase operand
    all_positions = list(puzzle.label_to_pos.keys())
    all_tile_ids = list(range(1, GRID_SIZE * GRID_SIZE)) # 1 to 15
    max_tile_id = (GRID_SIZE * GRID_SIZE) - 1

    initial_state_map = {puzzle.pos_to_label[pos]: int(puzzle.initial_board[pos]) for pos in np.ndindex(puzzle.initial_board.shape)}

    target_id = None

    if challenge_type == 'track_to_origin':
        target_id = random.choice(all_tile_ids)

    elif challenge_type == 'identify_from_origin':
        start_pos_label = random.choice(all_positions)
        target_id = initial_state_map[start_pos_label]
        # If by chance you select an empty slot, choose again
        while target_id == EMPTY_SLOT_ID:
            start_pos_label = random.choice(all_positions)
            target_id = initial_state_map[start_pos_label]

    elif challenge_type == 'return_to_origin_count':
        # Randomly select one as a bias target to increase confusion
        target_id = random.choice(all_tile_ids)

    # 3. Generate *biased* video operations
    puzzle.generate_biased_sequence(num_ops, relevant_tile_id=target_id)

    question = ""
    correct_answer = ""
    options = []

    # 4. Construct the truth map (now *after simulation*)
    final_state_map = {puzzle.pos_to_label[pos]: int(puzzle.final_board[pos]) for pos in np.ndindex(puzzle.final_board.shape)}
    # The initial state mapping has not changed

    if challenge_type == 'track_to_origin':
        # Question is predetermined (target_id)
        final_pos_label = next(label for label, tid in final_state_map.items() if tid == target_id)
        initial_pos_label = next(label for label, tid in initial_state_map.items() if tid == target_id)

        question = f"The number {target_id} is at position {final_pos_label} at the end. What was the *starting position* of this tile?"
        correct_answer = initial_pos_label
        options = generate_position_options(correct_answer, all_positions)

    elif challenge_type == 'identify_from_origin':
        # Problems are predetermined (start_pos_label, target_id)
        question = f"Which number (shown at the end) *started* at position {start_pos_label}?"
        correct_answer = str(target_id)
        options = generate_numeric_options(correct_answer, max_val=max_tile_id)

    elif challenge_type == 'return_to_origin_count':
        # "How many blocks are back in place?"
        count = 0
        for tile_id in all_tile_ids:
            start_pos = next(label for label, tid in initial_state_map.items() if tid == tile_id)
            end_pos = next(label for label, tid in final_state_map.items() if tid == tile_id)
            if start_pos == end_pos:
                count += 1

        question = f"How many tiles (1-{max_tile_id}) ended in the same position they started in?"
        correct_answer = str(count)
        options = generate_numeric_options(correct_answer, max_val=max_tile_id)

    video_filename = f"{challenge_type}_{challenge_id}.mp4"
    data = {
        "id": challenge_id, "challenge_type": challenge_type, "grid_size": GRID_SIZE,
        "question": question, "options": options, "correct_answer_value": correct_answer,
        "correct_answer_label": chr(ord('A') + options.index(correct_answer)),
        "video_filename": video_filename, "video_filepath": os.path.join(OUTPUT_VIDEO_DIR, video_filename),
        "puzzle_state": puzzle # passed to VideoGenerator
    }
    return data

# --- 6. Parallel Processing Worker (multi-process worker) ---
def process_single_challenge(challenge_id, challenge_type): # [--- MODIFIED ---]
    try:
        # [--- MODIFIED ---] passes in challenge_type
        challenge_data = generate_challenge_data(challenge_id, challenge_type)

        # Pass puzzle_state to VideoGenerator and remove it from the final data
        puzzle_state_obj = challenge_data.pop("puzzle_state")
        vg = VideoGenerator(puzzle_state_obj)
        vg.data = challenge_data # Inject data to save
        vg.generate_video()

        # --- Format SFT and RL ---
        question_text = challenge_data['question'] + "\n" + "\n".join([f"{chr(ord('A')+i)}. {opt}" for i, opt in enumerate(challenge_data['options'])])
        video_server_path = os.path.join(VIDEO_PREFIX_IN_JSON, challenge_data['video_filename']).replace("\\", "/")

        sft = {"type":"intermedia_sft", "messages":[{"role":"system","content":[{"type":"text","text":"You are a helpful assistant.","loss":False}]},{"role":"user","content":[{"type":"video","uuid":str(uuid.uuid4()),"video":video_server_path},{"type":"text","text":question_text,"loss":False}]},{"role":"assistant","content":[{"type":"text","text":challenge_data['correct_answer_label'],"loss":True}]}],"extra":{"id":challenge_data['id'],"task":challenge_data['challenge_type'],"data_type":"video","data_source":"Synthetic_Video_Sliding_Puzzle","original_video_path":video_server_path}}
        rl = {"problem_id":challenge_data['id'],"problem":f"<video>\n{question_text}","data_type":"video","problem_type":challenge_data['challenge_type'],"videos":[video_server_path],"data_source":"Synthetic_Video_Sliding_Puzzle","answer":challenge_data['correct_answer_label']}

        # Metadata
        metadata = {
            "problem_id":challenge_data['id'],"problem":f"<video>\n{question_text}","data_type":"video","problem_type":challenge_data['challenge_type'],"videos":[video_server_path],"data_source":"Synthetic_Video_Sliding_Puzzle","answer":challenge_data['correct_answer_label'],
            "id": challenge_data['id'], "challenge_type": challenge_data['challenge_type'],
            "initial_board_map": {puzzle_state_obj.pos_to_label[pos]: int(puzzle_state_obj.initial_board[pos]) for pos in np.ndindex(puzzle_state_obj.initial_board.shape)},
            "final_board_map": {puzzle_state_obj.pos_to_label[pos]: int(puzzle_state_obj.final_board[pos]) for pos in np.ndindex(puzzle_state_obj.final_board.shape)},
            "move_history": puzzle_state_obj.move_history,
            "question_data": challenge_data
        }

        return sft, rl, metadata
    except Exception as e:
        return (challenge_id, f"Error in processing {challenge_type}: {e}")

# --- 7. Main Execution Logic (main execution logic) ---
def main():
    # [--- MODIFIED ---] uses NUM_PER_TYPE
    total_jobs = len(CHALLENGE_TYPES) * NUM_PER_TYPE
    print(f"Starting dataset generation...")
    print(f"Base output directory: {BASE_OUTPUT_DIR}")
    print(f"Workers: {NUM_WORKERS}")
    print(f"Challenge Types: {len(CHALLENGE_TYPES)} ({', '.join(CHALLENGE_TYPES)})")
    print(f"Videos per Type: {NUM_PER_TYPE}")
    print(f"Total Videos: {total_jobs}")

    os.makedirs(OUTPUT_VIDEO_DIR, exist_ok=True)

    results = []

    with concurrent.futures.ProcessPoolExecutor(max_workers=NUM_WORKERS) as executor:
        futures = {}
        job_id = 0
        # [--- MODIFIED ---] Submit tasks in a loop
        for challenge_type in CHALLENGE_TYPES:
            for _ in range(NUM_PER_TYPE):
                # Pass job_id and challenge_type
                future = executor.submit(process_single_challenge, job_id, challenge_type)
                futures[future] = (job_id, challenge_type)
                job_id += 1

        for future in tqdm(concurrent.futures.as_completed(futures), total=total_jobs, desc="Generating Challenges"):
            results.append(future.result())

    print("\nWriting to JSONL files...")
    sft_recs, rl_recs, meta_recs, failed = [], [], [], []
    for res in results:
        if isinstance(res, tuple) and len(res) == 2:
            failed.append(res)
        elif res is not None:
             sft_recs.append(res[0]); rl_recs.append(res[1]); meta_recs.append(res[2])
        else:
             failed.append((-1, "Unknown error, result was None"))

    for path, data in zip([SFT_OUTPUT_FILE, RL_OUTPUT_FILE, METADATA_OUTPUT_FILE], [sft_recs, rl_recs, meta_recs]):
        with open(path, 'w') as f:
            for rec in data:
                f.write(json.dumps(rec) + '\n')

    print(f"\nSuccessfully generated {len(sft_recs)} challenges.")
    print(f"Videos: '{OUTPUT_VIDEO_DIR}/'\nSFT data: '{SFT_OUTPUT_FILE}'\nRL data: '{RL_OUTPUT_FILE}'\nMetadata: '{METADATA_OUTPUT_FILE}'")

    if failed:
        print(f"\nWARNING: {len(failed)} tasks failed.")
        for task_id, err in failed:
            print(f"  - Task {task_id}: {err}")

if __name__ == "__main__":
    main()
